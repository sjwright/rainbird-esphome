#!/usr/bin/env python3
"""Write the entity tables in README.md from the kind table.

`components/rainbird/entity_kinds.py` lists every entity the component can create. This
fills the part of README.md between the `entities:start` and `entities:end` markers from
it, so the README cannot list an entity that does not exist or miss one that does.

    python3 tools/gen_docs.py

`--check` writes nothing and exits 1 when the README is out of date. The Python tests run
the same comparison.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys
import types

REPO = Path(__file__).resolve().parents[1]
COMPONENT = REPO / "components" / "rainbird"
README = REPO / "README.md"
START = "<!-- entities:start (generated by tools/gen_docs.py; do not edit by hand) -->"
END = "<!-- entities:end -->"


def _load_kinds():
    """Import the pure module without ESPHome, the way tests/python/conftest.py does."""
    if "rainbird" not in sys.modules:
        package = types.ModuleType("rainbird")
        package.__path__ = [str(COMPONENT)]
        package.__package__ = "rainbird"
        sys.modules["rainbird"] = package
    from rainbird import entity_kinds

    return entity_kinds


def _type(kind) -> str:
    text = kind.domain
    if kind.limits is not None:
        minimum, maximum, _ = kind.limits
        text += f", {minimum} to {maximum}"
        if kind.unit:
            text += f" {kind.unit}"
    elif kind.unit:
        text += f", {kind.unit}"
    return text


def _writes(kind, ek) -> str:
    return {
        ek.Write.NONE: "read-only",
        ek.Write.LOCAL: "kept on the device",
        ek.Write.COMMAND: "command",
        ek.Write.SCHEDULE_PAGE: "schedule page",
    }[kind.write]


def _table(ek, scope, *, hub: bool) -> list[str]:
    head = ["Platform key", "Type", "Default name", "Writes", "Notes"]
    if hub:
        head = ["Hub key", *head[:2], "By default", *head[2:]]
    lines = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    for kind in ek.KINDS:
        if kind.scope is not scope:
            continue
        row = [f"`{kind.key}`", _type(kind), f"`{kind.default_name}`", _writes(kind, ek), kind.doc]
        if hub:
            row = [f"`{ek.hub_key(kind)}`", *row[:2], "yes" if kind.default else "", *row[2:]]
        lines.append("| " + " | ".join(row) + " |")
    return lines


def render() -> str:
    ek = _load_kinds()
    lines = [START, ""]
    lines.append("### Zone entities")
    lines.append("")
    lines.append("Set under a zone or in `zone_defaults` by hub key, or written by hand as a")
    lines.append("`platform: rainbird` entry with `zone:` and the platform key.")
    lines.append("")
    lines += _table(ek, ek.Scope.ZONE, hub=True)
    lines.append("")
    lines.append("### Program entities")
    lines.append("")
    lines.append("Set under a program or in `program_defaults` by hub key, or written by hand with")
    lines.append("`program:` and the platform key.")
    lines.append("")
    lines += _table(ek, ek.Scope.PROGRAM, hub=True)
    lines.append("")
    lines.append("### Controller entities")
    lines.append("")
    lines.append(
        "These are only written by hand, as `platform: rainbird` entries under the type's domain."
    )
    lines.append("")
    lines += _table(ek, ek.Scope.CONTROLLER, hub=False)
    lines.append("")
    lines.append(END)
    return "\n".join(lines)


def updated(text: str) -> str:
    """README text with the generated block replaced."""
    start = text.index(START)
    end = text.index(END) + len(END)
    return text[:start] + render() + text[end:]


def stale() -> bool:
    text = README.read_text()
    return updated(text) != text


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 if out of date")
    args = parser.parse_args()
    if not stale():
        return 0
    if args.check:
        print("README.md entity tables are out of date. Run: python3 tools/gen_docs.py")
        return 1
    README.write_text(updated(README.read_text()))
    print("wrote README.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
