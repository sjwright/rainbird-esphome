#!/usr/bin/env python3
"""Write the C++ headers that come from the Python tables.

`components/rainbird/entity_kinds.py` is the one kind table and `models.py` holds the
model's limits. This writes what the C++ side needs from them:

    components/rainbird/entity_kind.h    the EntityKind enum and the kind table rows
    components/rainbird/model_limits.h   zone, program and value limits

Run it after changing either Python file:

    python3 tools/gen_kinds.py

`--check` writes nothing and exits 1 when a header is out of date. The Python tests
run the same comparison, so CI fails on a stale header.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys
import types

REPO = Path(__file__).resolve().parents[1]
COMPONENT = REPO / "components" / "rainbird"


def _load_tables():
    """Import the pure modules without ESPHome, the way tests/python/conftest.py does."""
    if "rainbird" not in sys.modules:
        package = types.ModuleType("rainbird")
        package.__path__ = [str(COMPONENT)]
        package.__package__ = "rainbird"
        sys.modules["rainbird"] = package
    from rainbird import entity_kinds, models

    return entity_kinds, models


_HEADER = """\
#pragma once

// Generated by tools/gen_kinds.py from {source}. Do not edit: change the Python and run the tool.

#include <cstdint>

namespace esphome::rainbird {{

"""

_FOOTER = """\

}  // namespace esphome::rainbird
"""


def render_entity_kind() -> str:
    entity_kinds, _ = _load_tables()
    lines = [_HEADER.format(source="entity_kinds.py")]
    lines.append("// One value per row of entity_kinds.py (KindId).\n")
    lines.append("enum class EntityKind : uint8_t {\n")
    for kind_id in entity_kinds.KindId:
        lines.append(f"  {kind_id.name} = {int(kind_id)},\n")
    lines.append("};\n\n")
    lines.append('// Zone 0 and program 255 mean "this binding does not use that index".\n')
    lines.append('// Program 0 is program A, so 0 cannot mean "none".\n')
    lines.append(f"static constexpr uint8_t NO_ZONE = {entity_kinds.NO_ZONE};\n")
    lines.append(f"static constexpr uint8_t NO_PROGRAM = {entity_kinds.NO_PROGRAM};\n\n")
    lines.append(
        "// The kind table, one X(kind, field, write) per kind in enum order. entity_values.cpp\n"
    )
    lines.append(
        "// expands it into KindInfo rows: what each kind shows and polls, and how it writes.\n"
    )
    lines.append("// clang-format off\n")
    lines.append("#define RAINBIRD_ENTITY_KINDS(X) \\\n")
    rows = sorted(entity_kinds.KINDS, key=lambda kind: int(kind.kind_id))
    for position, kind in enumerate(rows):
        field = f"Field::{kind.field}" if kind.field else "NO_FIELD"
        end = " \\\n" if position + 1 < len(rows) else "\n"
        lines.append(
            f"  X(EntityKind::{kind.kind_id.name}, {field}, WritePath::{kind.write.name}){end}"
        )
    lines.append("// clang-format on\n")
    lines.append(_FOOTER)
    return "".join(lines)


def render_model_limits() -> str:
    _, models = _load_tables()
    model = models.ESP_TM2
    rows = [
        ("uint8_t", "TM2_ZONES", model.zones, ""),
        ("uint8_t", "TM2_PROGRAMS", len(model.letters), "A is wire program 0"),
        ("uint8_t", "TM2_STARTS", model.starts, "start slots per program"),
        ("uint16_t", "TM2_SEASONAL_MIN_PERCENT", model.seasonal_min_percent, ""),
        ("uint16_t", "TM2_SEASONAL_MAX_PERCENT", model.seasonal_max_percent, ""),
        ("uint16_t", "TM2_RAIN_DELAY_MAX_DAYS", model.rain_delay_max_days, ""),
        (
            "uint8_t",
            "TM2_RUN_MAX_MINUTES",
            model.run_max_minutes,
            "39, 4B and 3A take minutes in one byte",
        ),
    ]
    lines = [_HEADER.format(source="models.py")]
    lines.append(f"// The {model.name}. The YAML side checks a config against the same numbers.\n")
    for ctype, name, value, note in rows:
        if note:
            lines.append(f"// {note[0].upper()}{note[1:]}.\n")
        lines.append(f"static constexpr {ctype} {name} = {value};\n")
    lines.append(_FOOTER)
    return "".join(lines)


def outputs() -> dict[Path, str]:
    return {
        COMPONENT / "entity_kind.h": render_entity_kind(),
        COMPONENT / "model_limits.h": render_model_limits(),
    }


def stale() -> list[Path]:
    """The generated headers that do not match the Python tables."""
    return [
        path for path, text in outputs().items() if not path.exists() or path.read_text() != text
    ]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 if out of date")
    args = parser.parse_args()
    out_of_date = stale()
    if args.check:
        for path in out_of_date:
            print(f"{path.relative_to(REPO)} is out of date. Run: python3 tools/gen_kinds.py")
        return 1 if out_of_date else 0
    for path in out_of_date:
        path.write_text(outputs()[path])
        print(f"wrote {path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
